import { serve } from "https://deno.land/std@0.168.0/http/server.ts";

const corsHeaders = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Headers": "authorization, x-client-info, apikey, content-type, x-supabase-client-platform, x-supabase-client-platform-version, x-supabase-client-runtime, x-supabase-client-runtime-version",
};

serve(async (req) => {
  if (req.method === "OPTIONS") return new Response(null, { headers: corsHeaders });

  try {
    const { text } = await req.json();
    if (!text || typeof text !== "string" || text.trim().length === 0) {
      return new Response(JSON.stringify({ error: "Text is required" }), {
        status: 400,
        headers: { ...corsHeaders, "Content-Type": "application/json" },
      });
    }

    const wordCount = text.trim().split(/\s+/).length;
    if (wordCount > 5000) {
      return new Response(JSON.stringify({ error: "Text exceeds 5,000 word limit" }), {
        status: 400,
        headers: { ...corsHeaders, "Content-Type": "application/json" },
      });
    }

    const LOVABLE_API_KEY = Deno.env.get("LOVABLE_API_KEY");
    if (!LOVABLE_API_KEY) throw new Error("LOVABLE_API_KEY not configured");

    const response = await fetch("https://ai.gateway.lovable.dev/v1/chat/completions", {
      method: "POST",
      headers: {
        Authorization: `Bearer ${LOVABLE_API_KEY}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        model: "google/gemini-3-flash-preview",
        messages: [
          {
            role: "system",
            content: `You are an AI content detection expert. Analyze the provided text and determine if it was generated by AI or written by a human.

For each sentence, assign an AI probability score from 0-100 (0 = definitely human, 100 = definitely AI).

Also calculate:
- overallScore: weighted average AI probability (0-100)
- perplexity: estimated text perplexity (lower = more predictable/AI-like, typical AI: 20-40, human: 60-120)
- burstiness: sentence length variation (lower = more uniform/AI-like, typical AI: 0.2-0.4, human: 0.5-0.9)

Look for these AI indicators:
- Overly uniform sentence structure
- Lack of colloquialisms or personal voice
- Predictable transitions ("Furthermore", "Moreover", "In conclusion")
- Perfect grammar without natural hesitations
- Generic, non-specific examples
- Balanced paragraph lengths

Respond ONLY with valid JSON, no markdown.`,
          },
          {
            role: "user",
            content: text,
          },
        ],
        tools: [
          {
            type: "function",
            function: {
              name: "report_detection",
              description: "Report AI detection analysis results",
              parameters: {
                type: "object",
                properties: {
                  overallScore: { type: "number", description: "Overall AI probability 0-100" },
                  perplexity: { type: "number", description: "Estimated perplexity score" },
                  burstiness: { type: "number", description: "Burstiness score 0-1" },
                  sentences: {
                    type: "array",
                    items: {
                      type: "object",
                      properties: {
                        text: { type: "string" },
                        score: { type: "number", description: "AI probability 0-100" },
                      },
                      required: ["text", "score"],
                      additionalProperties: false,
                    },
                  },
                },
                required: ["overallScore", "perplexity", "burstiness", "sentences"],
                additionalProperties: false,
              },
            },
          },
        ],
        tool_choice: { type: "function", function: { name: "report_detection" } },
      }),
    });

    if (!response.ok) {
      if (response.status === 429) {
        return new Response(JSON.stringify({ error: "Rate limited, please try again later." }), {
          status: 429, headers: { ...corsHeaders, "Content-Type": "application/json" },
        });
      }
      if (response.status === 402) {
        return new Response(JSON.stringify({ error: "Credits required." }), {
          status: 402, headers: { ...corsHeaders, "Content-Type": "application/json" },
        });
      }
      const t = await response.text();
      console.error("AI gateway error:", response.status, t);
      throw new Error("AI analysis failed");
    }

    const data = await response.json();
    const toolCall = data.choices?.[0]?.message?.tool_calls?.[0];
    if (!toolCall) throw new Error("No analysis result");

    const result = JSON.parse(toolCall.function.arguments);

    return new Response(JSON.stringify(result), {
      headers: { ...corsHeaders, "Content-Type": "application/json" },
    });
  } catch (e) {
    console.error("detect error:", e);
    return new Response(JSON.stringify({ error: e instanceof Error ? e.message : "Unknown error" }), {
      status: 500,
      headers: { ...corsHeaders, "Content-Type": "application/json" },
    });
  }
});
